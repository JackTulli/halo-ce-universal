#!/usr/bin/env python3
"""Writes the Win32 bridge of the Xbox build (tools/xbox_build.py).

nxdk implements the Win32 functions the game calls (CreateFileA, ReadFile,
CreateEventA, ...) with the cdecl convention; the game, written against the
XDK, calls them as __stdcall. For each function named in
port/xbox/win32_names.txt this writes, from its prototype in
port/include/xdk/xdk_pdb.h (whose raw C types both sides' headers accept):

- nx_win32.c, compiled against nxdk's headers: a cdecl nxb_<name> that
  calls nxdk's <name>;
- win32_thunks.c, compiled against the XDK declarations: the __stdcall
  <name> the game links, calling nxb_<name>;
- nx_win32.h: the nxb_ prototypes, for both.

    python tools/xbox_win32_bridge.py --header port/include/xdk/xdk_pdb.h
        --names port/xbox/win32_names.txt --output-dir build/xbox
"""

import argparse
import re
import sys
from pathlib import Path

PROTOTYPE = re.compile(r"^(?P<result>[A-Za-z_][\w \*]*?)\s*__stdcall\s+(?P<name>\w+)\((?P<parameters>[^)]*)\);$")
ENUM = re.compile(r"\benum _\w+\b")


def parse_prototypes(header: Path):
    prototypes = {}
    for line in header.read_text(encoding="utf-8", errors="replace").splitlines():
        match = PROTOTYPE.match(line.strip())
        if match:
            prototypes[match.group("name")] = (match.group("result").strip(), match.group("parameters").strip())
    return prototypes


def parameters(text: str, redirect_paths: bool = False):
    """(declaration with names, argument list, redirect buffers) for a
    prototype's parameters; with redirect_paths, each string parameter goes
    through platform_redirect_path (the disc's writable folders)"""
    if text in ("", "void"):
        return "void", "", ""
    declared, passed, buffers = [], [], []
    for index, parameter in enumerate(part.strip() for part in text.split(",")):
        name = f"a{index}"
        if "(*" in parameter:
            declared.append(parameter.replace("(*", f"(*{name}", 1))
        else:
            declared.append(f"{parameter} {name}")
        if redirect_paths and parameter.replace(" ", "") == "constchar*":
            buffers.append(f"\tchar redirected{index}[260];")
            passed.append(f"platform_redirect_path({name}, redirected{index})")
        else:
            passed.append(name)
    return ", ".join(declared), ", ".join(passed), "\n".join(buffers)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--names", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    names = []
    for line in args.names.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            words = line.split()
            names.append((words[0], "bridge-only" in words[1:], "path" in words[1:]))
    prototypes = parse_prototypes(args.header)
    missing = [name for name, _, _ in names if name not in prototypes]
    if missing:
        sys.exit(f"{args.header} has no __stdcall prototype for: {', '.join(missing)}")

    header = ["/* generated by tools/xbox_win32_bridge.py: nxdk's Win32 functions, as cdecl nxb_ functions */",
              "#ifndef __HALO_XBOX_NX_WIN32_H", "#define __HALO_XBOX_NX_WIN32_H", ""]
    bridge = ["/* generated by tools/xbox_win32_bridge.py: nxdk's Win32 functions (cdecl), for the __stdcall",
              "thunks in win32_thunks.c and the hand-written ones in port/xbox/src/xbox_kernel.c */",
              "#include <windows.h>", '#include "nx_win32.h"', ""]
    thunks = ["/* generated by tools/xbox_win32_bridge.py: the __stdcall Win32 functions the game links,",
              "forwarding to nxdk's cdecl ones (nx_win32.c) */",
              '#include "platform.h"', '#include "nx_win32.h"', ""]
    for name, bridge_only, redirect_paths in names:
        result, parameter_text = prototypes[name]
        declared, passed, _ = parameters(parameter_text)
        _, redirected, buffers = parameters(parameter_text, redirect_paths)
        # nxdk's headers spell the XDK's enumerations differently
        bridge_result, bridge_declared = ENUM.sub("int", result), ENUM.sub("int", declared)
        returns = "return " if result != "void" else ""
        header.append(f"{bridge_result} __cdecl nxb_{name}({bridge_declared});")
        bridge += [f"{bridge_result} __cdecl nxb_{name}({bridge_declared})", "{", f"\t{returns}{name}({passed});", "}", ""]
        if not bridge_only:
            thunks += [f"{result} __stdcall {name}({declared})", "{"]
            if buffers:
                thunks += [buffers, ""]
            thunks += [f"\tplatform_trace(\"{name}\");", f"\t{returns}nxb_{name}({redirected});", "}", ""]
    header += ["", "#endif", ""]

    args.output_dir.mkdir(parents=True, exist_ok=True)
    for file_name, lines in (("nx_win32.h", header), ("nx_win32.c", bridge), ("win32_thunks.c", thunks)):
        path = args.output_dir / file_name
        text = "\n".join(lines)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
